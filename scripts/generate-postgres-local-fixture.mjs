// Regenerates scripts/local-development-fixture.postgres.sql from the D1
// fixture. The data is identical; only SQLite syntax that PostgreSQL rejects
// is converted (backtick identifiers, 1/0 in boolean columns), and identity
// sequences are advanced past the fixture's explicit ids.
// Run: node scripts/generate-postgres-local-fixture.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
let sql = readFileSync(`${root}scripts/local-development-fixture.sql`, "utf8").replaceAll("`", "\"")

// [exact text, replacement, expected occurrences]
const booleans = [
  ["'ADMIN', 1, CURRENT_TIMESTAMP", "'ADMIN', TRUE, CURRENT_TIMESTAMP", 1],
  ["'PCOM', 1, CURRENT_TIMESTAMP", "'PCOM', TRUE, CURRENT_TIMESTAMP", 1],
  ["@example.test', 1, 'example.test'", "@example.test', TRUE, 'example.test'", 2],
  ["  1, 1, 'Committee-confirmed relationship'", "  TRUE, 1, 'Committee-confirmed relationship'", 1],
  ["'New', '', 0, ''", "'New', '', FALSE, ''", 2],
  ["'Follow-up Due', 'Local Development Admin', 1, '2026-09-25'", "'Follow-up Due', 'Local Development Admin', TRUE, '2026-09-25'", 1],
  ["'Skipped', '', 0, ''", "'Skipped', '', FALSE, ''", 1],
]
for (const [from, to, expected] of booleans) {
  const found = sql.split(from).length - 1
  if (found !== expected) throw new Error(`Expected ${expected} of ${from}; found ${found}. Update the generator for the changed D1 fixture.`)
  sql = sql.split(from).join(to)
}

const tables = [...new Set([...sql.matchAll(/INSERT INTO "([a-z_]+)" \(\s*"id"/g)].map(match => match[1]))]
const sequences = tables.map(table => `SELECT setval(pg_get_serial_sequence('${table}', 'id'), (SELECT max(id) FROM "${table}"));`).join("\n")

writeFileSync(`${root}scripts/local-development-fixture.postgres.sql`,
  `-- GENERATED by scripts/generate-postgres-local-fixture.mjs from scripts/local-development-fixture.sql.\n`
  + `-- Fictional local-development data only. Do not edit by hand.\n\n${sql.trimEnd()}\n\n${sequences}\n`)
console.log(`Wrote PostgreSQL fixture; sequences advanced for: ${tables.join(", ")}`)
