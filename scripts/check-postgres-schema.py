#!/usr/bin/env python3
"""Check the independent PostgreSQL snapshot against the final D1 snapshot."""

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SQLITE = ROOT / "drizzle/meta/0026_snapshot.json"
PG = ROOT / "drizzle-postgres/meta/0000_snapshot.json"
MIGRATION = next((ROOT / "drizzle-postgres").glob("0000_*.sql"))
UTC_DEFAULT = "to_char(timezone('UTC', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')"


def load_tables(path):
    return json.loads(path.read_text())["tables"]


def index_signature(index, postgres=False):
    columns = index["columns"]
    if postgres:
        columns = [item["expression"] for item in columns]
    return (columns, index["isUnique"], index.get("where"))


source = load_tables(SQLITE)
target = {name.removeprefix("public."): table for name, table in load_tables(PG).items()}
source_boolean_names = Counter(re.findall(r'integer\("([^"]+)", \{ mode: "boolean" \}\)', (ROOT / "db/schema.ts").read_text()))
target_boolean_names = Counter(column_name for table in target.values() for column_name, column in table["columns"].items() if column["type"] == "boolean")
errors = []
rows = []
differences = []

if set(source) != set(target):
    errors.append(f"table names differ: source-only={set(source)-set(target)}, target-only={set(target)-set(source)}")
if source_boolean_names != target_boolean_names:
    errors.append("SQLite boolean-mode columns differ from PostgreSQL boolean columns")

for name in sorted(set(source) & set(target)):
    left, right = source[name], target[name]
    if set(left["columns"]) != set(right["columns"]):
        errors.append(f"{name}: column names differ")
    for column in sorted(set(left["columns"]) & set(right["columns"])):
        a, b = left["columns"][column], right["columns"][column]
        for field in ("primaryKey", "notNull"):
            if a[field] != b[field]:
                errors.append(f"{name}.{column}: {field} differs")
        expected_type = "serial" if a.get("autoincrement") else "boolean" if a["type"] == "integer" and b["type"] == "boolean" else a["type"]
        if b["type"] != expected_type:
            errors.append(f"{name}.{column}: unexpected type {a['type']} -> {b['type']}")
        if b["type"] == "boolean" and a["type"] == "integer":
            differences.append(f"{name}.{column}: SQLite integer boolean -> PostgreSQL boolean")
        if b["type"] == "serial":
            differences.append(f"{name}.{column}: SQLite AUTOINCREMENT integer -> PostgreSQL serial")
        expected_default = UTC_DEFAULT if a.get("default") == "CURRENT_TIMESTAMP" else a.get("default")
        if b.get("default") != expected_default:
            errors.append(f"{name}.{column}: default differs: {a.get('default')} -> {b.get('default')}")
        if expected_default == UTC_DEFAULT:
            differences.append(f"{name}.{column}: UTC CURRENT_TIMESTAMP text formatting preserved")
    for key in ("foreignKeys", "checkConstraints", "compositePrimaryKeys", "uniqueConstraints"):
        if left[key] != right[key]:
            errors.append(f"{name}: {key} differs")
    if set(left["indexes"]) != set(right["indexes"]):
        errors.append(f"{name}: index names differ")
    for index_name in set(left["indexes"]) & set(right["indexes"]):
        if index_signature(left["indexes"][index_name]) != index_signature(right["indexes"][index_name], True):
            errors.append(f"{name}.{index_name}: index columns, uniqueness, or predicate differ")
    rows.append((name, len(left["columns"]), len(left["foreignKeys"]), len(left["indexes"]), len(left["checkConstraints"])))

sql = MIGRATION.read_text()
if len(re.findall(r'^CREATE TABLE ', sql, re.M)) != len(target):
    errors.append("migration CREATE TABLE count differs from snapshot")
if len(re.findall(r'^CREATE (?:UNIQUE )?INDEX ', sql, re.M)) != sum(row[3] for row in rows):
    errors.append("migration CREATE INDEX count differs from snapshot")

if errors:
    print("FAIL: " + "\nFAIL: ".join(errors), file=sys.stderr)
    sys.exit(1)

summary = [
    "# PostgreSQL schema parity: SQLite 0026 → PostgreSQL 0000",
    "",
    "Generated by `python3 scripts/check-postgres-schema.py --write-report` from the Drizzle snapshots.",
    "The check compares every table and column name, nullability, default, primary key,",
    "foreign key, unique constraint, CHECK constraint, index expression, uniqueness, and partial predicate.",
    "",
    f"**Result:** {len(rows)}/{len(source)} tables; {sum(r[1] for r in rows)} columns; "
    f"{sum(r[2] for r in rows)} foreign keys; {sum(r[3] for r in rows)} indexes; "
    f"{sum(r[4] for r in rows)} CHECK constraints. No omitted objects.",
    "",
    "## Intentional storage mappings",
    "",
    "- 40 SQLite AUTOINCREMENT integer primary keys become PostgreSQL `serial` so explicit historical IDs remain loadable and future IDs use sequences. Reset each sequence after data migration.",
    "- 11 SQLite integer boolean fields become PostgreSQL `boolean`; a later data migration must map 0/1 to false/true.",
    "- 52 SQLite UTC `CURRENT_TIMESTAMP` text defaults become UTC `YYYY-MM-DD HH:MM:SS` text expressions. This keeps seconds precision and the existing timezone convention.",
    "- All other integer and text columns retain their storage type. Date/time and JSON-named fields remain text because the source uses mixed date formats, empty-string sentinels, and JSON strings. Typed conversion belongs to a separately reviewed later step.",
    "- PostgreSQL B-tree replaces SQLite's default index method; index keys, uniqueness, expressions, and predicates are retained.",
    "- PostgreSQL truncates 24 Drizzle-generated foreign-key names beyond 63 bytes. The staging verifier checks their truncated names and all 55 relationships; no constraint is omitted.",
    "",
    "## Table-by-table comparison",
    "",
    "| Table | Columns | FKs | Indexes | CHECKs | Parity |",
    "| --- | ---: | ---: | ---: | ---: | --- |",
]
summary += [f"| `{name}` | {columns} | {fks} | {indexes} | {checks} | Pass |" for name, columns, fks, indexes, checks in rows]
summary += ["", "The complete field-level mapping is asserted by the comparison script against both committed snapshots.", ""]

if "--write-report" in sys.argv:
    (ROOT / "docs/postgres-schema-comparison.md").write_text("\n".join(summary))
print(f"PASS: {len(rows)} tables, {sum(r[1] for r in rows)} columns, {sum(r[2] for r in rows)} FKs, {sum(r[3] for r in rows)} indexes, {sum(r[4] for r in rows)} CHECKs; {len(differences)} intentional field mappings")
